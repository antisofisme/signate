/**
 * Renders a lucide-react icon component based on icon name string
 * @param iconName - The name of the icon to render (e.g., 'Home', 'Settings', 'User')
 * @param props - Optional props to pass to the icon component (size, className, color, etc.)
 * @returns A React component or null if icon not found
 *
 * @example
 * renderIcon('Home', { size: 24, className: 'text-blue-500' })
 * renderIcon('Settings', { size: 20 })
 * renderIcon('User')
 */
export const renderIcon = (
  iconName: string | null | undefined,
  props?: IconProps
): React.ReactElement | null => {
  if (!iconName) {
    return <AlertCircle size={props?.size || 24} className="text-gray-400" />;
  }

  const IconComponent = iconRegistry[iconName];

  if (!IconComponent) {
    console.warn(`Icon "${iconName}" not found in icon registry. Using fallback icon.`);
    return <AlertCircle size={props?.size || 24} className="text-gray-400" />;
  }

  return <IconComponent {...props} />;
};

/**
 * Get an icon component directly without rendering
 * Useful for cases where you need to pass the component to other functions
 * @param iconName - The name of the icon component
 * @returns The icon component or null if not found
 *
 * @example
 * const Icon = getIcon('Home');
 * <Icon size={24} />
 */
export const getIcon = (iconName: string | null | undefined): IconComponent | null => {
  if (!iconName) {
    return AlertCircle as IconComponent;
  }

  const IconComponent = iconRegistry[iconName];

  if (!IconComponent) {
    console.warn(`Icon "${iconName}" not found in icon registry. Using fallback icon.`);
    return AlertCircle as IconComponent;
  }

  return IconComponent as IconComponent;
};

/**
 * Check if an icon exists in the registry
 * @param iconName - The name of the icon to check
 * @returns true if the icon exists, false otherwise
 *
 * @example
 * if (iconExists('Home')) {
 *   renderIcon('Home')
 * }
 */
export const iconExists = (iconName: string | null | undefined): boolean => {
  if (!iconName) return false;
  return iconName in iconRegistry;
};

/**
 * Get all available icon names from the registry
 * @returns Array of all icon names
 *
 * @example
 * const allIcons = getAllIconNames();
 * console.log(allIcons); // ['AlertCircle', 'Home', 'Settings', ...]
 */
export const getAllIconNames = (): string[] => {
  return Object.keys(iconRegistry);
};

export default {
  renderIcon,
  getIcon,
  iconExists,
  getAllIconNames,
};
